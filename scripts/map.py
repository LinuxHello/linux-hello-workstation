#!/usr/bin/env python3
"""Draws the dependency map of the open issues as a Mermaid diagram in Markdown.

Reads one JSON object on stdin: {"issues": [{number, title, labels: [{name}]}], "triage": "<text of
issues/triage.tsv>"} and writes the Markdown to stdout. It opens no file and runs no command
(scripts/map.sh does both), so it can be tested with a fixture.

Only open issues that are linked by a "blocked by" edge in the triage file are drawn, grouped
by the connected set they belong to. The other open issues are listed under the diagram.
"""
import json
import re
import sys
from collections import Counter

KIND_ORDER = ["yours", "ready", "waits", "active"]
KIND_TEXT = {
    "yours": "your decision or a spike",
    "ready": "can be briefed or implemented now",
    "waits": "waits for another issue",
    "active": "being worked on or in review",
}


def kind(labels, blocked):
    """What the issue is waiting for, from its labels and whether it is blocked."""
    names = {label["name"] for label in labels}
    if "type:spike" in names or "one-way-door" in names:
        return "yours"
    if names & {"status:in-progress", "status:in-review"}:
        return "active"
    if blocked or "status:blocked" in names:
        return "waits"
    return "ready"


def container(labels):
    """The container label of the issue without its prefix, or 'other'."""
    for label in labels:
        if label["name"].startswith("container:"):
            return label["name"].split(":", 1)[1]
    return "other"


def short(title, width=44):
    """The title cut to a width, safe inside a Mermaid quoted label."""
    text = re.sub(r'["\[\]<>{}`|]', "'", title).strip()
    return text if len(text) <= width else text[: width - 1].rstrip() + "..."


def edges_of(triage, open_numbers):
    """The (blocker, blocked) pairs of the triage file where both issues are open."""
    pairs = []
    for line in triage.splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        fields = line.split("\t")
        if len(fields) < 4 or fields[3] in ("-", ""):
            continue
        blocked = int(fields[0])
        for blocker in fields[3].split(","):
            blocker = int(blocker)
            if blocked in open_numbers and blocker in open_numbers:
                pairs.append((blocker, blocked))
    return pairs


def components(numbers, pairs):
    """The connected sets of issue numbers, each sorted, ordered by their lowest number."""
    parent = {n: n for n in numbers}

    def find(n):
        while parent[n] != n:
            parent[n] = parent[parent[n]]
            n = parent[n]
        return n

    for a, b in pairs:
        parent[find(a)] = find(b)
    groups = {}
    for n in numbers:
        groups.setdefault(find(n), []).append(n)
    return sorted((sorted(g) for g in groups.values()), key=lambda g: g[0])


def render(data):
    """The Markdown for the given issues and triage text."""
    issues = {i["number"]: i for i in data["issues"]}
    pairs = edges_of(data["triage"], set(issues))
    linked = sorted({n for pair in pairs for n in pair})
    blocked_now = {b for _, b in pairs}
    out = ["# Dependency map of the open issues", ""]
    out.append("Generated by `make map` from `issues/triage.tsv` and the open issues. An arrow means "
               "the issue it points to waits for the one it leaves. Do not edit by hand.")
    out.append("")
    out.append("```mermaid")
    out.append("flowchart TD")
    for n in linked:
        issue = issues[n]
        label = f"#{n} {short(issue['title'])}"
        out.append(f'  n{n}["{label}"]')
    for index, group in enumerate(components(linked, pairs), start=1):
        names = Counter(container(issues[n]["labels"]) for n in group)
        title = names.most_common(1)[0][0]
        out.append(f'  subgraph g{index}["{title}"]')
        out.extend(f"    n{n}" for n in group)
        out.append("  end")
    for a, b in pairs:
        out.append(f"  n{a} --> n{b}")
    out.append("  classDef yours fill:#EEEDFE,stroke:#534AB7,color:#26215C")
    out.append("  classDef ready fill:#E1F5EE,stroke:#0F6E56,color:#04342C")
    out.append("  classDef waits fill:#F1EFE8,stroke:#5F5E5A,color:#2C2C2A")
    out.append("  classDef active fill:#FAEEDA,stroke:#854F0B,color:#412402")
    for n in linked:
        out.append(f"  class n{n} {kind(issues[n]['labels'], n in blocked_now)}")
    out.append("```")
    out.append("")
    out.append("Purple: your decision or a spike. Green: can be briefed or implemented now. "
               "Grey: waits for another issue. Amber: being worked on or in review.")
    rest = [n for n in sorted(issues) if n not in linked]
    out += ["", "## Open issues with no dependency", ""]
    by_kind = {k: [] for k in KIND_ORDER}
    for n in rest:
        by_kind[kind(issues[n]["labels"], False)].append(n)
    for k in KIND_ORDER:
        if by_kind[k]:
            out.append(f"**{KIND_TEXT[k]}**")
            out.append("")
            out.extend(f"- #{n} {short(issues[n]['title'], 70)}" for n in by_kind[k])
            out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


if __name__ == "__main__":
    sys.stdout.write(render(json.load(sys.stdin)))
